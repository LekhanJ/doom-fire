def do_fire():
    if space_held:
        for i in range(len(fire_pixels)-1, (cols*rows)-cols-1, -1):
            fire_pixels[i] = 36
    else:
        for i in range(len(fire_pixels)-1, (cols*rows)-cols-1, -1):
            fire_pixels[i] = 0
    for x in range(cols):
        for y in range(1, rows):
            spread_fire(y * cols + x)

def spread_fire(frm):
    rand = random.randint(0, 3) 
    to = frm - cols + (1 - rand)
    if 0 <= to < len(fire_pixels):
        fire_pixels[to] = max(0, fire_pixels[frm] - (rand & 1))
    
while running:
    for event in pygame.event.get():
        if event.type == pygame.QUIT:
            running = False
            
        elif event.type == pygame.KEYDOWN:
            if event.key == pygame.K_SPACE:
                space_held = True
        
        elif event.type == pygame.KEYUP:
            if event.key == pygame.K_SPACE:
                space_held = False
                
    screen.fill("black")
    
    do_fire()
    
    for i, pixel in enumerate(fire_pixels):
        color = color_map[pixel]
        
        rect = pygame.Rect(
            (i % cols) * cell_size,
            (math.floor(i / cols)) * cell_size,
            cell_size,
            cell_size
        )
        
        pygame.draw.rect(screen, color, rect)

    pygame.display.flip()
    clock.tick(60)

